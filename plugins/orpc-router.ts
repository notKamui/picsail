import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import type { Plugin, ViteDevServer } from 'vite'

interface ProcedureFile {
  filePath: string
  route: string[]
}

interface RouterNode {
  procedures: Map<string, string>
  children: Map<string, RouterNode>
}

export interface ORPCRouterPluginOptions {
  proceduresDir: string
  outputFile: string
}

function createNode(): RouterNode {
  return { procedures: new Map(), children: new Map() }
}

function toRouteSegment(segment: string): string {
  if (!/^[A-Za-z_$][\w$]*(?:-[A-Za-z0-9_$]+)*$/.test(segment)) {
    throw new Error(`Invalid oRPC route segment: ${segment}`)
  }

  return segment.replaceAll(/-([A-Za-z0-9_$])/g, (_, character: string) => character.toUpperCase())
}

async function findProcedures(directory: string, root: string): Promise<ProcedureFile[]> {
  const entries = await readdir(directory, { withFileTypes: true })
  const files: ProcedureFile[] = []

  for (const entry of entries) {
    const absolutePath = path.join(directory, entry.name)

    if (entry.isDirectory()) {
      files.push(...(await findProcedures(absolutePath, root)))
      continue
    }

    if (!entry.isFile() || !entry.name.endsWith('.rpc.ts')) continue

    const relativePath = path.relative(root, absolutePath).replaceAll(path.sep, '/')
    const route = relativePath.slice(0, -'.rpc.ts'.length).split(/[/.]/).map(toRouteSegment)

    if (route.some((segment) => segment === '__proto__')) {
      throw new Error(`Invalid oRPC procedure filename: ${relativePath}`)
    }

    files.push({ filePath: absolutePath, route })
  }

  return files
}

function buildRouter(files: ProcedureFile[], outputPath: string): string {
  const root = createNode()

  for (const file of files) {
    let node = root

    for (const segment of file.route.slice(0, -1)) {
      let child = node.children.get(segment)
      if (!child) {
        child = createNode()
        node.children.set(segment, child)
      }

      if (node.procedures.has(segment)) {
        throw new Error(`oRPC route conflicts with a procedure: ${file.route.join('.')}`)
      }

      node = child
    }

    const procedure = file.route.at(-1)!
    if (node.procedures.has(procedure) || node.children.has(procedure)) {
      throw new Error(`Duplicate oRPC route: ${file.route.join('.')}`)
    }

    node.procedures.set(procedure, file.filePath)
  }

  const imports = files
    .map((file, index) => {
      const relativePath = path
        .relative(path.dirname(outputPath), file.filePath)
        .replaceAll(path.sep, '/')
      const modulePath = relativePath.startsWith('.') ? relativePath : `./${relativePath}`
      return `import procedure${index} from '${modulePath}'`
    })
    .join('\n')

  const procedureNames = new Map(files.map((file, index) => [file.filePath, `procedure${index}`]))

  function serialize(node: RouterNode, indent = 0): string {
    const entries = [
      ...[...node.procedures].map(([key, filePath]) => `${key}: ${procedureNames.get(filePath)}`),
      ...[...node.children].map(([key, child]) => `${key}: ${serialize(child, indent + 2)}`),
    ]

    if (entries.length === 0) return '{}'

    const entryIndent = ' '.repeat(indent + 2)
    const closingIndent = ' '.repeat(indent)
    return `{\n${entries.map((entry) => `${entryIndent}${entry},`).join('\n')}\n${closingIndent}}`
  }

  return `// This file is generated by the oRPC Vite plugin. Do not edit.
${imports}

export const router = ${serialize(root)}
`
}

async function generate(proceduresDir: string, outputPath: string) {
  const foundFiles = await findProcedures(proceduresDir, proceduresDir)
  const files = foundFiles.reduce<ProcedureFile[]>((sorted, file) => {
    const index = sorted.findIndex((entry) => entry.filePath.localeCompare(file.filePath) > 0)
    if (index === -1) sorted.push(file)
    else sorted.splice(index, 0, file)
    return sorted
  }, [])
  const content = buildRouter(files, outputPath)

  await mkdir(path.dirname(outputPath), { recursive: true })

  try {
    if ((await readFile(outputPath, 'utf8')) === content) return false
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error
  }

  await writeFile(outputPath, content)
  return true
}

export function orpcRouterPlugin(options: ORPCRouterPluginOptions): Plugin {
  let proceduresDir: string
  let outputPath: string
  let server: ViteDevServer | undefined
  let updateTimer: ReturnType<typeof setTimeout> | undefined

  async function update() {
    if (!server) return
    clearTimeout(updateTimer)
    updateTimer = setTimeout(() => {
      void generate(proceduresDir, outputPath).catch((error: unknown) => {
        server?.config.logger.error(
          `[orpc-router] ${error instanceof Error ? error.message : String(error)}`,
        )
      })
    }, 30)
  }

  return {
    name: 'picsail:orpc-router',
    enforce: 'pre',
    async configResolved(config) {
      proceduresDir = path.resolve(config.root, options.proceduresDir)
      outputPath = path.resolve(config.root, options.outputFile)
      await generate(proceduresDir, outputPath)
    },
    configureServer(devServer) {
      server = devServer
      devServer.watcher.add(proceduresDir)
      devServer.watcher.on('add', update)
      devServer.watcher.on('unlink', update)
    },
  }
}
